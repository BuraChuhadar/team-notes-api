"""Run Alembic on the transaction supplied by the application."""

from alembic import context
from sqlalchemy.engine import Connection

from app.models import Base

config = context.config
connection = config.attributes.get("connection")
if not isinstance(connection, Connection):
    raise RuntimeError("Run migrations with app.database.migration_config(connection).")


def include_object(
    object_: object,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: object | None,
) -> bool:
    # This retained ledger belongs to deployments predating Alembic. Future
    # autogenerated revisions must preserve it rather than propose dropping it.
    return not (type_ == "table" and name == "schema_migrations")


context.configure(
    connection=connection,
    target_metadata=Base.metadata,
    compare_type=True,
    include_object=include_object,
)
with context.begin_transaction():
    context.run_migrations()
